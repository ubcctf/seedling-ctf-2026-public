import random
import sys

print("To solve this challenge, send the bytes represented by the hex!")
print("Hint: write a script (e.g. `pwntools`) to automate the process.\n")

# except newline (0x0a)
valid_bytes = [i for i in range(256) if i != 0x0a]

for level in range(50):
    if level < 3:
        length = random.randint(1, 5)
        printable = True
    elif level < 15:
        length = random.randint(4, 8)
        printable = False
    elif level < 30:
        length = random.randint(9, 14)
        printable = False
    else:
        length = random.randint(15, 30)
        printable = False

    if printable:
        data = bytes(random.randint(0x21, 0x7e) for _ in range(length))
    else:
        data = bytes(random.choice(valid_bytes) for _ in range(length))

    hex_data = " ".join(f"0x{byte:02x}" for byte in data)

    print(f"Level {level + 1}: {hex_data}; Send {len(data)} bytes:")

    received = sys.stdin.buffer.readline().rstrip(b"\n") # ignore the \n generated by clicking enter

    if received == data:
        print("Correct!\n")
    else:
        print("Wrong!")
        exit(1)

with open("flag.txt", "r") as f:
    print(f.read().rstrip())